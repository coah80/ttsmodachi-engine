pub fn field(rom: Rom, us: u32) -> u32 {
    let row = FIELDS
        .binary_search_by_key(&us, |r| r.0)
        .expect("Speech field");
    match rom {
        Rom::Us | Rom::Eu => FIELDS[row].1,
        Rom::Kr => FIELDS[row].2,
    }
}

pub fn backend_field(rom: Rom, us: u32) -> u32 {
    if rom == Rom::Kr && us >= 0x4bc0 {
        us - 4
    } else {
        us
    }
}
