use std::cell::Cell;
use tts_core::rom_region::Rom;
thread_local! { static CONTEXT: Cell<Option<(Rom,u8)>> = const { Cell::new(None) }; }
pub fn configure(rom: Rom, language: u8) {
    CONTEXT.set(Some((rom, language)));
}
pub fn context() -> (Rom, u8) {
    CONTEXT.get().expect("regional ROM boot context")
}
pub fn address(us: u32) -> u32 {
    let i = ADDRESSES
        .binary_search_by_key(&us, |row| row.0)
        .unwrap_or_else(|_| panic!("unmapped regional boot address {us:#x}"));
    let row = ADDRESSES[i];
    let value = if context().0 == Rom::Eu { row.1 } else { row.2 };
    assert_ne!(value, 0, "unmapped regional boot address {us:#x}");
    value
}
pub fn guest(entry: u32) -> u32 {
    let eu = context().0 == Rom::Eu;
    ADDRESSES
        .iter()
        .find(|row| if eu { row.1 == entry } else { row.2 == entry })
        .map_or(entry, |row| row.0)
}
pub fn canonical(entry: u32) -> u32 {
    if ENTRIES.binary_search(&entry).is_ok() {
        return entry;
    }
    let eu = context().0 == Rom::Eu;
    ADDRESSES
        .iter()
        .find(|row| if eu { row.1 == entry } else { row.2 == entry })
        .map_or(entry, |row| row.0)
}
